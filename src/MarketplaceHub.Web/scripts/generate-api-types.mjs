// API-GUVENLIK-8: TypeScript types of the panel's API, generated from the contract file the API's tests keep
// (tests/MarketplaceHub.Application.Tests/ApiContract/openapi.v1.json). Types only: no runtime client, no fetch wrapper
// (hubApi and the query-key factory stay what they are). Dependency-free on purpose: it reads the schemas the document
// actually contains - objects, arrays, string/number/boolean/null unions, enums, additionalProperties, $ref and oneOf -
// file answers (a binary string: Blob), answers without a body (void) and deprecated parameters (@deprecated).
//
//   npm run gen:api-types     writes src/shared/api/generated/api-types.ts
//   npm run check:api-types   fails when that file is not what the contract file generates (CI)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const contract = resolve(web, '../../tests/MarketplaceHub.Application.Tests/ApiContract/openapi.v1.json')
const target = resolve(web, 'src/shared/api/generated/api-types.ts')

const document = JSON.parse(readFileSync(contract, 'utf8'))
const schemas = document.components?.schemas ?? {}
const responses = document.components?.responses ?? {}

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const key = name => (identifier.test(name) ? name : JSON.stringify(name))
const refName = ref => {
  const name = ref.split('/').pop()
  if (!ref.startsWith('#/components/schemas/') || !(name in schemas)) throw new Error(`Unknown $ref ${ref}`)
  return name
}
const union = parts => [...new Set(parts)].join(' | ')
const literal = value => JSON.stringify(value)

/** The TypeScript type of a schema; `indent` is the indentation of the line the type starts on. */
function typeOf(schema, indent = '') {
  if (!schema || typeof schema !== 'object' || Object.keys(schema).length === 0) return 'unknown'
  if (schema.$ref) return refName(schema.$ref)
  if (schema.oneOf) return union(schema.oneOf.map(option => wrap(typeOf(option, indent))))
  if (schema.anyOf) return union(schema.anyOf.map(option => wrap(typeOf(option, indent))))
  if (schema.allOf) return schema.allOf.map(part => wrap(typeOf(part, indent))).join(' & ')
  if (schema.enum) return union(schema.enum.map(literal))
  const types = schema.type === undefined ? (schema.properties ? ['object'] : []) : [schema.type].flat()
  if (types.length === 0) return 'unknown'
  return union(types.map(type => single(type, schema, indent)))
}

function single(type, schema, indent) {
  switch (type) {
    case 'null': return 'null'
    case 'string': return 'string'
    case 'integer':
    case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'array': return `${wrap(typeOf(schema.items, indent))}[]`
    case 'object': return objectOf(schema, indent)
    default: throw new Error(`Unsupported type ${type}`)
  }
}

// A union or intersection inside an array or another union keeps its own parentheses.
function wrap(type) {
  let depth = 0
  for (const character of type) {
    if ('{(<['.includes(character)) depth++
    else if ('})>]'.includes(character)) depth--
    else if (depth === 0 && (character === '|' || character === '&')) return `(${type})`
  }
  return type
}

function objectOf(schema, indent) {
  const properties = Object.entries(schema.properties ?? {})
  const required = new Set(schema.required ?? [])
  const additional = schema.additionalProperties
  const extra = additional === undefined || additional === false ? null : additional === true ? 'unknown' : typeOf(additional, indent)
  if (properties.length === 0) return `Record<string, ${extra ?? 'unknown'}>`
  const inner = `${indent}  `
  const lines = properties.map(([name, property]) => `${comment(property, inner)}${inner}${key(name)}${required.has(name) ? '' : '?'}: ${typeOf(property, inner)}`)
  const body = `{\n${lines.join('\n')}\n${indent}}`
  if (extra === null) return body
  // Extension members of any kind (ApiProblem): an index signature that every declared member fits.
  if (extra === 'unknown') return `{\n${lines.join('\n')}\n${inner}[member: string]: unknown\n${indent}}`
  return `${body} & Record<string, ${extra}>`
}

function comment(schema, indent) {
  const text = schema && typeof schema === 'object' && !schema.$ref ? schema.description : undefined
  return text ? `${indent}/** ${text.replaceAll('*/', '*\\/')} */\n` : ''
}

const out = []
out.push('// Generated by scripts/generate-api-types.mjs from tests/MarketplaceHub.Application.Tests/ApiContract/openapi.v1.json.')
out.push('// Do not edit: change the API, regenerate the contract file (MARKETPLACEHUB_UPDATE_OPENAPI=1) and run npm run gen:api-types.')
out.push(`// ${document.info?.title ?? 'API'} ${document.info?.version ?? ''}: ${Object.keys(schemas).length} schemas.`.trimEnd())
out.push('')

for (const [name, schema] of Object.entries(schemas)) {
  out.push(`${comment(schema, '')}export type ${name} = ${typeOf(schema)}`)
  out.push('')
}

// Operations by operationId: method, route, parameters, body, the success answer and the error statuses.
const operations = []
for (const [path, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!operation.operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`)
    operations.push({ path, method: method.toUpperCase(), operation })
  }
}
operations.sort((a, b) => (a.operation.operationId < b.operation.operationId ? -1 : a.operation.operationId > b.operation.operationId ? 1 : 0))

const resolveResponse = response => (response?.$ref ? responses[response.$ref.split('/').pop()] : response)
// A parameter the document marks deprecated (an old paging parameter kept for old browser tabs) says so in its comment.
const parameterComment = (parameter, indent) =>
  parameter.deprecated
    ? `${indent}/** @deprecated ${(parameter.description ?? 'Kept for old clients.').replaceAll('*/', '*\\/')} */\n`
    : comment(parameter, indent)
const params = (operation, where, indent) => {
  const list = (operation.parameters ?? []).filter(parameter => parameter.in === where)
  if (list.length === 0) return 'Record<string, never>'
  return `{\n${list.map(parameter => `${parameterComment(parameter, `${indent}  `)}${indent}  ${key(parameter.name)}${parameter.required ? '' : '?'}: ${typeOf(parameter.schema, `${indent}  `)}`).join('\n')}\n${indent}}`
}
// A success answer that is not JSON: a file's bytes (a string in format binary) are a Blob, a text a string.
const binary = schema => {
  const resolved = schema?.$ref ? schemas[refName(schema.$ref)] : schema
  return resolved?.type === 'string' && resolved.format === 'binary'
}
const fileAnswer = content => {
  const media = Object.entries(content ?? {}).filter(([type]) => type !== 'application/json')
  if (media.length === 0) return null
  return media.every(([, value]) => binary(value.schema)) ? 'Blob' : 'string'
}

out.push('/** Every operation of the API by its operationId. Undeclared answers are `unknown`; an answer without a body is `void`; a file is a `Blob`. */')
out.push('export interface ApiOperations {')
for (const { path, method, operation } of operations) {
  const indent = '    '
  const success = Object.entries(operation.responses).filter(([status]) => status.startsWith('2') || status.startsWith('3'))
  const declared = success.find(([, response]) => resolveResponse(response).content?.['application/json'])
  const file = declared ? null : success.find(([, response]) => fileAnswer(resolveResponse(response).content))
  const answer = declared
    ? typeOf(resolveResponse(declared[1]).content['application/json'].schema, indent)
    : file ? fileAnswer(resolveResponse(file[1]).content)
    : success.length > 0 && success.every(([status, response]) => status !== '200' && !resolveResponse(response).content) ? 'void' : 'unknown'
  const status = declared ? Number(declared[0]) : file ? Number(file[0]) : success.length > 0 ? Number(success[0][0]) : 200
  const errors = Object.keys(operation.responses).filter(code => !code.startsWith('2') && !code.startsWith('3')).map(Number)
  const body = operation.requestBody?.content?.['application/json']?.schema
  out.push(`  ${key(operation.operationId)}: {`)
  out.push(`    method: ${literal(method)}`)
  out.push(`    path: ${literal(path)}`)
  out.push(`    pathParams: ${params(operation, 'path', indent)}`)
  out.push(`    query: ${params(operation, 'query', indent)}`)
  out.push(`    headers: ${params(operation, 'header', indent)}`)
  out.push(`    body: ${body ? typeOf(body, indent) : 'never'}`)
  out.push(`    status: ${status}`)
  out.push(`    response: ${answer}`)
  out.push(`    errorStatus: ${errors.length > 0 ? errors.join(' | ') : 'never'}`)
  if (operation['x-paging']) out.push(`    paging: ${literal(operation['x-paging'])}`)
  out.push('  }')
}
out.push('}')
out.push('')
out.push('export type ApiOperationId = keyof ApiOperations')
out.push("/** The success answer of an operation: `ApiResponse<'getConnections'>`. */")
out.push("export type ApiResponse<Id extends ApiOperationId> = ApiOperations[Id]['response']")
out.push("/** The JSON body an operation reads. */")
out.push("export type ApiRequestBody<Id extends ApiOperationId> = ApiOperations[Id]['body']")
out.push("/** The query parameters an operation reads. */")
out.push("export type ApiQuery<Id extends ApiOperationId> = ApiOperations[Id]['query']")
out.push('')

const generated = out.join('\n')
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8').replaceAll('\r\n', '\n') } catch { /* missing reads as different */ }
  if (current !== generated) {
    console.error(`${target} is not what ${contract} generates: run npm run gen:api-types and commit the result.`)
    process.exit(1)
  }
  console.log(`api-types.ts matches the contract file (${operations.length} operations, ${Object.keys(schemas).length} schemas).`)
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, generated)
  console.log(`Wrote ${target} (${operations.length} operations, ${Object.keys(schemas).length} schemas).`)
}
